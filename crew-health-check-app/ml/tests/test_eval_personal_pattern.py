MS_PER_DAY = 86_400_000


def strict_json(text):
    def refuse(name):
        raise ValueError(f'{name} is not valid JSON')

    return json.loads(text, parse_constant=refuse)


def without_created_at(model):
    return {key: value for key, value in model.items() if key != 'createdAt'}


def card_body(text):
    return '\n'.join(line for line in text.splitlines() if not line.startswith('Generated by '))


def routine_by_day(readings, crew_id, now_ms):
    """One routine value per indicator and day, the last one counting, as lastReadingPerDay."""
    daily = {}
    for reading in sorted(readings, key=lambda entry: entry['atMs']):
        if reading['crewId'] != crew_id or reading['atMs'] > now_ms or reading.get('purpose') == 'recheck':
            continue
        daily.setdefault(reading['indicator'], {})[reading['day']] = reading['value']
    return daily


@unittest.skipUnless(HAVE_PACKAGES, NEEDS)
class RulesCopyTests(unittest.TestCase):
    """The Python copy of the rules gives the scenario files' alerts on readings."""

    def test_every_scenario_gives_its_expected_reading_alerts(self):
        rules = evaluation.load_rules()
        indicators = evaluation.load_indicators()
        simulated = set(indicators)
        usable, _ = evaluation.rules_on_readings(rules, simulated)
        usable_ids = {rule['id'] for rule in usable}
        superseded_by = {old: rule['id'] for rule in rules for old in rule.get('supersedes', [])}
        checked = 0
        for path in sorted(SEED_DIR.glob('*.json')):
            if path.name == 'index.json':
                continue
            scenario = json.loads(path.read_text(encoding='utf-8'))
            today = scenario['missionDay']
            now_ms = (today - 1) * MS_PER_DAY + NINE_AM_MS
            for member in scenario['crew']:
                daily = routine_by_day(scenario['readings'], member['id'], now_ms)
                bases = {
                    indicator: pattern.baseline(values, indicators[indicator]['minSpread'], today)
                    for indicator, values in daily.items()
                    if indicators[indicator]['cadenceDays'] == 1
                }
                met = set(evaluation.rule_alerts(usable, daily, bases, today))
                expected = {
                    alert['ruleId']
                    for alert in scenario['expectedAlerts']
                    if alert['crewId'] == member['id'] and alert['ruleId'] in usable_ids
                }
                self.assertTrue(expected <= met, f"{path.name} {member['id']}: {sorted(met)} misses {sorted(expected - met)}")
                for extra in met - expected:
                    self.assertIn(superseded_by.get(extra), expected, f'{path.name} {member["id"]}: unexpected {extra}')
                checked += 1
        self.assertGreater(checked, 0)

    def test_rules_on_feeds_and_models_are_left_out(self):
        usable, skipped = evaluation.rules_on_readings(evaluation.load_rules(), set(pattern.INDICATORS))
        self.assertIn('R-SLEEP-01', [rule['id'] for rule in usable])
        for rule_id in ('R-CO2-01', 'R-RAD-01', 'R-RAD-03'):
            self.assertIn(rule_id, skipped)


@unittest.skipUnless(HAVE_PACKAGES, NEEDS)
class SimulationTests(unittest.TestCase):
    def setUp(self):
        self.indicators = evaluation.load_indicators()
        self.kinds = evaluation.variants()
        self.today = 50
        self.daily = evaluation.simulate_history('c1', random.Random('test'), self.today, self.indicators, self.kinds)

    def test_variants_differ_only_on_shift_days_and_shifted_readings(self):
        clean = self.daily['clean']
        for name, amounts in self.kinds:
            for indicator in pattern.INDICATORS:
                for day in range(1, self.today + 1):
                    same = clean[indicator][day] == self.daily[name][indicator][day]
                    if day <= self.today - evaluation.SHIFT_DAYS or indicator not in amounts:
                        self.assertTrue(same, f'{name} {indicator} day {day}')

    def test_a_shift_moves_the_reading_in_its_direction(self):
        for entry in evaluation.PATTERNS:
            name = f"{entry['id']}@3"
            for indicator, direction in entry['directions'].items():
                change = self.daily[name][indicator][self.today] - self.daily['clean'][indicator][self.today]
                self.assertGreaterEqual(change * direction, 0, f'{name} {indicator}')

    def test_shifts_never_enter_the_baseline(self):
        evaluated = evaluation.evaluate_history(self.daily, self.today, self.indicators, [], seed=42)
        first, last = pattern.baseline_window(self.today)
        self.assertLess(last, self.today - evaluation.SHIFT_DAYS + 1)
        self.assertEqual(len(evaluated['rows']), last - first + 1)

    def test_wilson_interval_holds_the_rate(self):
        for count, total in ((0, 50), (3, 50), (50, 50)):
            low, high = evaluation.wilson(count, total)
            self.assertLessEqual(low, count / total)
            self.assertGreaterEqual(high, count / total)
            self.assertGreaterEqual(low, 0)
            self.assertLessEqual(high, 1)


