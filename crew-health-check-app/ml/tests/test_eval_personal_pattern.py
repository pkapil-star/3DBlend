@unittest.skipUnless(HAVE_PACKAGES, NEEDS)
class SmallRunTests(unittest.TestCase):
    """Two short runs with the same seed write the same files."""

    def test_the_same_seed_gives_the_same_files(self):
        with tempfile.TemporaryDirectory() as folder:
            outputs = []
            for name, created in (('first', 'one'), ('second', 'two')):
                target = Path(folder) / name
                evaluation.run(
                    seed=42, histories_per_profile=3, app_models_dir=target / 'app', artifacts_dir=target / 'artifacts',
                    reports_dir=target / 'reports', created_at=created,
                )
                outputs.append(target)
            first, second = outputs
            self.assertEqual(
                without_created_at(strict_json((first / 'app' / 'personal-pattern-v1.json').read_text(encoding='utf-8'))),
                without_created_at(strict_json((second / 'app' / 'personal-pattern-v1.json').read_text(encoding='utf-8'))),
            )
            self.assertEqual(
                (first / 'artifacts' / 'personal-pattern-v1-parity.json').read_bytes(),
                (second / 'artifacts' / 'personal-pattern-v1-parity.json').read_bytes(),
            )
            self.assertEqual(
                card_body((first / 'reports' / 'personal-pattern-v1.md').read_text(encoding='utf-8')),
                card_body((second / 'reports' / 'personal-pattern-v1.md').read_text(encoding='utf-8')),
            )


@unittest.skipUnless(HAVE_PACKAGES, NEEDS)
class ExportTests(unittest.TestCase):
    """The committed files are exactly what one full run writes."""

    @classmethod
    def setUpClass(cls):
        cls.folder = tempfile.TemporaryDirectory()
        target = Path(cls.folder.name)
        evaluation.run(seed=42, app_models_dir=target / 'app', artifacts_dir=target / 'artifacts', reports_dir=target / 'reports')
        cls.model = strict_json((target / 'app' / 'personal-pattern-v1.json').read_text(encoding='utf-8'))
        cls.parity = strict_json((target / 'artifacts' / 'personal-pattern-v1-parity.json').read_text(encoding='utf-8'))
        cls.card = (target / 'reports' / 'personal-pattern-v1.md').read_text(encoding='utf-8')

    @classmethod
    def tearDownClass(cls):
        cls.folder.cleanup()

    def test_the_committed_files_are_what_the_script_writes(self):
        committed = strict_json((evaluation.APP_MODELS_DIR / 'personal-pattern-v1.json').read_text(encoding='utf-8'))
        self.assertEqual(without_created_at(committed), without_created_at(self.model))
        self.assertEqual(
            strict_json((evaluation.ARTIFACTS_DIR / 'personal-pattern-v1-parity.json').read_text(encoding='utf-8')), self.parity
        )
        self.assertEqual(
            card_body((evaluation.REPORTS_DIR / 'personal-pattern-v1.md').read_text(encoding='utf-8')), card_body(self.card)
        )

    def test_the_model_file_has_the_planned_shape(self):
        model = self.model
        self.assertEqual((model['modelId'], model['version'], model['kind']), ('personal-pattern', 'v1', 'shrinkage-mahalanobis'))
        self.assertEqual(model['indicators'], list(pattern.INDICATORS))
        self.assertEqual((model['minIndicatorsToday'], model['minDays']), (4, 14))
        self.assertEqual(model['headline'], 'Unusual pattern for you')
        self.assertEqual(model['caveat'], 'Learned from your own readings. Tested only on simulated data. A second opinion only.')
        self.assertIs(model['evaluation']['simulated'], True)
        self.assertEqual(model['evaluation']['histories'], 3 * evaluation.HISTORIES_PER_PROFILE)
        self.assertEqual(len(model['evaluation']['detection']), len(evaluation.PATTERNS) * len(evaluation.SIZES))
        for entry in [model['evaluation']['falseNotice']] + model['evaluation']['detection']:
            for method in evaluation.METHODS:
                result = entry[method]
                self.assertEqual(result['of'], model['evaluation']['histories'])
                self.assertAlmostEqual(result['rate'], result['flagged'] / result['of'])
                self.assertLessEqual(result['ci95'][0], result['rate'])
                self.assertGreaterEqual(result['ci95'][1], result['rate'])

    def test_parity_cases_are_reproduced_by_the_python_model(self):
        for case in self.parity['matrixCases']:
            result = pattern.score_today(np.array(case['rows']), case['z'])
            self.assertEqual(result['squaredDistance'], case['squaredDistance'], case['id'])
            self.assertEqual(result['maxLoo'], case['maxLoo'], case['id'])
            self.assertEqual(result['notable'], case['notable'], case['id'])
        self.assertTrue(any(value < 0 for case in self.parity['matrixCases'] for value in case['contributions']))
        notable = [case['expected']['notable'] for case in self.parity['historyCases']]
        self.assertIn(True, notable)
        self.assertIn(False, [case['expected']['readiness']['ready'] for case in self.parity['historyCases']])

    def test_the_card_says_the_evaluation_is_simulated(self):
        self.assertIn('**Evaluated only on simulated data.**', self.card)
        self.assertIn('do not show that it notices real illness', self.card)
        for line in self.model['limitations']:
            self.assertIn(line, self.card)


if __name__ == '__main__':
    unittest.main()
